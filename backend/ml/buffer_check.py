"""Does a savings buffer change what a student can do? `python -m ml.buffer_check` (plan P7d).

D-27 left an optional savings buffer as future work: the forecast starts from RM 0, so a student
with real savings and little income looks At Risk for every purchase. Before spending an engine
round on it (it changes Engine 1's simulation and so Engine 2's labels), this measures how much
it would matter, on the three committed persona statements, with the served forecast network.

For each persona and each purchase on a small grid, the direct simulation of that purchase gives
the chance of running short, exactly the quantity Engine 2's label is built from (D-07). It is
run with no buffer and with a buffer. A buffer is emulated by adding it to the first month's
margin, which is what an opening balance does to every running total; no engine file changes.

Nothing here is a model score: it is the simulation, on three synthetic ledgers, and the report
says so. It is regenerated by this command and is never edited by hand.
"""

# ruff: noqa: E501  (the markdown template below has long table rows)

import argparse
import json
from datetime import timedelta
from pathlib import Path
from typing import Any

import app.engines.forecasting.service as service
from app.domain.csv_import import parse_csv
from app.domain.plan_builder import propose_plan
from app.engines.forecasting.serving import served_forecaster
from app.engines.forecasting.simulate import band
from app.engines.forecasting.summary import build_feature_inputs

PERSONA_DIR = Path(__file__).resolve().parents[2] / "data" / "personas"
PERSONAS = ("budget_conscious", "frequent_bnpl", "irregular_income")
BUFFERS_SEN = (0, 100_000, 300_000)  # RM 0, RM 1,000, RM 3,000
PRICES_SEN = (10_000, 30_000, 60_000, 100_000, 150_000)  # RM 100 ... RM 1,500
INSTALMENTS = (3, 6)
SEED = 20261021
PATHS = 1000


def ledger(persona: str) -> tuple[list[dict[str, Any]], Any]:
    preview = parse_csv((PERSONA_DIR / f"{persona}.csv").read_text(encoding="utf-8-sig"))
    rows = [
        {"date": r.date, "amount_sen": r.amount_sen, "type": r.type, "category": r.category_guess}
        for r in preview.rows
    ]
    return rows, max(r["date"] for r in rows) + timedelta(days=1)


def with_buffer(buffer_sen: int):
    """The simulator with an opening balance: the buffer joins the first month's margin."""
    original = service.simulate

    def simulate(*args, **kwargs):
        kwargs["month_to_date_sen"] = kwargs.get("month_to_date_sen", 0) + buffer_sen
        return original(*args, **kwargs)

    return original, simulate


def measure(persona: str, buffer_sen: int, forecaster) -> dict[str, Any]:
    rows, today = ledger(persona)
    original, patched = with_buffer(buffer_sen)
    service.simulate = patched
    try:
        cells, baseline = [], None
        for price in PRICES_SEN:
            for count in INSTALMENTS:
                proposal = propose_plan(
                    provider="spaylater",
                    purchase_date=today,
                    num_instalments=count,
                    total_price_sen=price,
                )
                built = build_feature_inputs(
                    rows, [], [], proposal, {}, today, forecaster, seed=SEED, paths=PATHS
                )
                if built is None:
                    raise RuntimeError(f"{persona}: the forecast is locked")
                baseline = built.p_without
                cells.append(
                    {
                        "price_sen": price,
                        "instalments": count,
                        "p_with": built.p_with,
                        "band": band(built.p_with),
                    }
                )
    finally:
        service.simulate = original
    return {
        "persona": persona,
        "buffer_sen": buffer_sen,
        "baseline_p": baseline,
        "baseline_band": band(baseline),
        "safe_cells": sum(c["band"] == "Safe" for c in cells),
        "cells": cells,
    }


def render(results: list[dict[str, Any]]) -> str:
    total = len(PRICES_SEN) * len(INSTALMENTS)
    lines = [
        "# Savings buffer check (plan P7d, Phase C)",
        "",
        "Generated by `cd backend && uv run python -m ml.buffer_check`; do not edit by hand.",
        "",
        "**What this is.** The direct simulation (the quantity Engine 2's label is built from, D-07) of "
        f"{total} purchases per persona on SPayLater (RM 100 to RM 1,500, 3 or 6 instalments), run with "
        "no savings buffer and with one, using the served forecast network. A buffer is an opening "
        "balance added to the first month's margin. **What it is not:** a model score, a result on real "
        "students, or a forecast of anyone's finances. It is three synthetic ledgers.",
        "",
        "| Persona | Buffer | Chance of running short before any purchase | Band | Purchases that reach Safe |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(
            f"| {r['persona']} | RM {r['buffer_sen'] // 100:,} | {r['baseline_p']:.1%} | "
            f"{r['baseline_band']} | {r['safe_cells']} of {total} |"
        )
    lines += ["", "## Every purchase", ""]
    for r in results:
        lines += [f"### {r['persona']}, buffer RM {r['buffer_sen'] // 100:,}", ""]
        lines += ["| Price | Instalments | Chance of running short | Band |", "|---|---|---|---|"]
        for c in r["cells"]:
            lines.append(
                f"| RM {c['price_sen'] // 100:,} | {c['instalments']} | {c['p_with']:.1%} | {c['band']} |"
            )
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=Path("../reports/buffer_check"))
    args = parser.parse_args(argv)
    forecaster = served_forecaster()
    results = [measure(p, b, forecaster) for p in PERSONAS for b in BUFFERS_SEN]
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "README.md").write_text(render(results) + "\n", encoding="utf-8", newline="\n")
    (args.out / "buffer_check.json").write_text(
        json.dumps(results, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    print(f"wrote {args.out / 'README.md'}")


if __name__ == "__main__":
    main()
